# Writes common/title_map_dc.inc: the SBDE08 value of every RBUE08 address and small-data displacement that the native code names
# through UC_ADDR(0x...), UC_SDA13(n) and UC_SDA2(n) (common/title.h).
#
# Usage: python -I tools/title_map.py --match <dolmatch out dir> --manual project/dc/title_manual.txt --out common/title_map_dc.inc <source files or folders...>
#
# An address resolves, in this order, through: title_manual.txt; a matched function entry; a function that is the same code in both
# programs (the address moves by the same offset); a data address pair seen at the same place of same-code functions.
# A displacement resolves through title_manual.txt, then through the pair with the most votes in sda_offsets.txt.
# What does not resolve is listed at the end of the file as a comment and is left out, so its use fails to compile (static_assert).
import argparse
import bisect
import re
import sys
from pathlib import Path


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--match", required=True)
    ap.add_argument("--manual")
    ap.add_argument("--out", required=True)
    ap.add_argument("sources", nargs="+")
    args = ap.parse_args()
    m = Path(args.match)

    entries = {}
    for line in (m / "matched_functions.txt").read_text(encoding="utf-8").splitlines():
        if line and not line.startswith("#"):
            p = line.split()
            entries[int(p[1], 16)] = (int(p[0], 16), p[2])
    same = []
    for line in (m / "same_code.txt").read_text(encoding="utf-8").splitlines():
        if line and not line.startswith("#"):
            p = line.split()
            same.append((int(p[0], 16), int(p[1], 16), int(p[2])))
    same.sort()
    same_starts = [s[0] for s in same]
    data = {}
    for line in (m / "data_addresses.txt").read_text(encoding="utf-8").splitlines():
        if line and not line.startswith("#"):
            p = line.split()
            best = p[1].split(":")
            second = int(p[2].split(":")[1]) if len(p) > 2 else 0
            data[int(p[0], 16)] = (int(best[0], 16), int(best[1]), second)
    sda = {"sda13": {}, "sda2": {}}
    for line in (m / "sda_offsets.txt").read_text(encoding="utf-8").splitlines():
        if line and not line.startswith("#"):
            p = line.split()
            best = p[2].split(":")
            second = int(p[3].split(":")[1]) if len(p) > 3 else 0
            sda[p[0]][int(p[1], 16)] = (int(best[0], 16), int(best[1]), second)
    manual_addr, manual_sda = {}, {"sda13": {}, "sda2": {}}
    if args.manual and Path(args.manual).exists():
        for raw in Path(args.manual).read_text(encoding="utf-8").splitlines():
            line = raw.split("#", 1)[0].split()
            if len(line) >= 3 and line[0] == "addr":
                manual_addr[int(line[1], 16)] = int(line[2], 16)
            elif len(line) >= 3 and line[0] in ("sda13", "sda2"):
                manual_sda[line[0]][int(line[1]) & 0xFFFF] = int(line[2])

    files = []
    for s in args.sources:
        p = Path(s)
        files += sorted(q for q in p.rglob("*") if q.suffix in (".cpp", ".h", ".hpp")) if p.is_dir() else [p]
    want_addr, want_sda = {}, {"sda13": {}, "sda2": {}}
    for f in files:
        text = f.read_text(encoding="utf-8", errors="replace")
        for h in re.findall(r"UC_ADDR\(\s*0x([0-9A-Fa-f]{8})u?\s*\)", text):
            want_addr.setdefault(int(h, 16), f.as_posix())
        for kind, n in re.findall(r"UC_(SDA13|SDA2)\(\s*(-?\d+)\s*\)", text):
            want_sda[kind.lower()].setdefault(int(n), f.as_posix())

    def signed(v):
        return v - 0x10000 if v & 0x8000 else v

    out, missing = [], []
    out.append("// Generated by tools/title_map.py from the outputs of tools/dolmatch.py. Do not edit: add hand-found values to project/dc/title_manual.txt.")
    out.append("// UC_TITLE_ADDR(<RBUE08 address>, <SBDE08 address>)   UC_TITLE_SDA13 / UC_TITLE_SDA2(<RBUE08 displacement>, <SBDE08 displacement>)")
    for a in sorted(want_addr):
        how = None
        if a in manual_addr:
            n, how = manual_addr[a], "manual"
        elif a in entries:
            n, how = entries[a][0], "function, " + entries[a][1]
        else:
            i = bisect.bisect_right(same_starts, a) - 1
            if i >= 0 and a < same[i][0] + 4 * same[i][2]:
                n, how = same[i][1] + (a - same[i][0]), "inside same-code function %08X" % same[i][0]
            elif a in data:
                n, votes, second = data[a]
                how = "data, %d votes%s" % (votes, (" (next candidate %d)" % second) if second else "")
        if how is None:
            missing.append("// MISSING UC_ADDR(0x%08X)   first use: %s" % (a, want_addr[a]))
        else:
            out.append("UC_TITLE_ADDR(0x%08X, 0x%08X)   // %s" % (a, n, how))
    for kind in ("sda13", "sda2"):
        for d in sorted(want_sda[kind]):
            key = d & 0xFFFF
            if key in manual_sda[kind]:
                out.append("UC_TITLE_%s(%d, %d)   // manual" % (kind.upper(), d, manual_sda[kind][key]))
            elif key in sda[kind]:
                n, votes, second = sda[kind][key]
                out.append("UC_TITLE_%s(%d, %d)   // %d votes%s" % (kind.upper(), d, signed(n), votes, (" (next candidate %d)" % second) if second else ""))
            else:
                missing.append("// MISSING UC_%s(%d)   first use: %s" % (kind.upper(), d, want_sda[kind][d]))
    Path(args.out).write_text("\n".join(out + missing) + "\n", encoding="utf-8")
    print("title map: %d addresses, %d displacements, %d missing" % (len(want_addr), sum(len(v) for v in want_sda.values()), len(missing)))
    for line in missing:
        print(line)


if __name__ == "__main__":
    main()
